// lohhausen/tools/bundle.mjs
// -----------------------------------------------------------------------------
// The engine is written as ES modules (used directly by Node tests). Browsers
// refuse module imports over file://, so this tiny bundler concatenates the
// engine into one classic script that exposes `window.LH`.
// Kept honest by tests/model.test.mjs: the checked-in bundle must equal a fresh build.
// -----------------------------------------------------------------------------
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const FILES = ['engine/sim.js', 'engine/game.js', 'engine/bots.js'];

export const EXPORTS = [
  'PARAMS', 'TOTAL_MONTHS', 'SESSIONS', 'MONTHS_PER_SESSION', 'initialState', 'cloneState',
  'step', 'runMonths', 'runToEnd', 'applyIntent', 'intentCost', 'patchOrder', 'fmtDM',
  'demandJustifiedStaff', 'unitCost', 'defaultOrders', 'computeDerived',
  'MEASURES', 'MEASURE_GROUPS', 'SECTORS', 'endSession', 'sessionBriefing', 'scoreGame', 'buildReport',
  'detectPatterns', 'isLastSession', 'sessionStartMonth', 'referenceProduction', 'eventStudy', 'teach', 'advisorNotes', 'sessionRecap',
  'PETITION_POOL', 'drawPetition',
  'BOTS', 'play', 'afford', 'planner', 'nextRandom', 'gauss', 'lerp', 'staffNeededForOutput', 'pushReport', 'pushHistory', 'addInbox',
  'doNothing', 'charles', 'mark', 'recreationFirst', 'factoryOnly', 'neglectMachinery', 'taxGrab', 'tourismSpam', 'balanced', 'chaos',
];

export function buildBundle() {
  const parts = FILES.map(f => {
    let src = readFileSync(join(root, f), 'utf8');
    src = src.replace(/^import[\s\S]*?from\s+'[^']+';$/gm, '');
    src = src.replace(/^export\s*\{[^}]*\};$/gm, '');
    src = src.replace(/^export\s+(const|let|function|class)/gm, '$1');
    return `// ── ${f} ─────────────────────────────────────────────────────────────\n${src}`;
  });
  return `// lohhausen/web/js/engine.bundle.js — GENERATED by tools/bundle.mjs; do not edit.
// Build with: node tools/bundle.mjs    (tests/model.test.mjs checks this is in sync)
(() => {
'use strict';
${parts.join('\n')}
window.LH = { ${EXPORTS.join(', ')} };
})();
`;
}

export function writeBundle() {
  const out = join(root, 'web', 'js', 'engine.bundle.js');
  const content = buildBundle();
  writeFileSync(out, content);
  return content;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('bundle.mjs')) {
  const c = writeBundle();
  console.log(`engine.bundle.js written (${(c.length / 1024).toFixed(1)} kB)`);
}
